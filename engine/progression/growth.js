// ============================================================
//  Рост по счёту — возможность движка: насколько сильнее n-й моб, страж, зверь...
//  Две части, можно вместе: проценты от базы (pct) и прибавка цифрой (flat) каждые every шагов.
//  Проценты растут вместе с базой — слабый удар остаётся слабым, сильный — сильным,
//  и никто не становится «всех убивающим» из-за большой прибавки цифрой.
//
//    grow(10, 100, { pct: 0.004 })              // 10 × (1 + 0.4)            = 14
//    grow(10, 100, { pct: 0.004, flat: 1, every: 25 })  // 10 × 1.4 + 1 × 4 = 18
//    grow([5, 10], 100, { pct: 0.01 })          // [10, 20] — и для «от … до»
//    growth(100, { pct: 0.004, flat: 1, every: 25 })    // { mult: 1.4, add: 4 } — сами множитель и прибавка
// ============================================================

export function growth(n, { pct = 0, flat = 0, every = 1 } = {}) {
  return { mult: 1 + pct * n, add: flat * Math.floor(n / every) };
}

// Применить рост к числу или паре [от, до]; round — округлять до целых
export function grow(base, n, rule = {}, round = true) {
  const { mult, add } = growth(n, rule);
  const f = (v) => (round ? Math.round(v * mult + add) : v * mult + add);
  return Array.isArray(base) ? base.map(f) : f(base);
}
