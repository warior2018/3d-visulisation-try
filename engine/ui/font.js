// Латинские буквы, которые выглядят как русские, рисуем теми же точками
for (const [lat, cyr] of [["A", "А"], ["B", "В"], ["E", "Е"], ["K", "К"], ["M", "М"], ["H", "Н"], ["O", "О"], ["P", "Р"], ["C", "С"], ["T", "Т"], ["X", "Х"]]) {
  G[lat] = G[cyr];
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;
const UNKNOWN = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]; // нет такой буквы — квадрат

export function glyph(ch) {
  return G[ch.toUpperCase()] || UNKNOWN;
}

// Ширина текста в точках экрана: 5 точек на букву + 1 точка промежутка, всё × масштаб
export function measureText(text, scale) {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}
