// ============================================================
//  «Мозги» (ИИ) существ — возможность движка. Каждое существо может
//  получить свой brain; игра каждый кадр зовёт:
//
//    const { walking, alerted } = e.brain.update(e, ctx, dt);
//
//  ctx — что мозгам нужно знать о мире (собирает игра):
//    entities  — все сущности (найти врага, не толпиться, поднять стадо);
//    navWorld  — { isSolid, version } для поиска пути (engine/ai/pathfinder.js);
//    combatFor(e) — колбэки для атак этого существа: { onUse, onHit, onMiss } (звук, анимация).
//  Ответ: walking — идёт ли (аниматору: Walk / Idle); alerted — кто разозлился (для лога).
//
//  Готовые мозги:
//    HostileBrain (hostile.js) — враг: ищет ближайшего, с кем враждует, идёт по пути, бьёт, поднимает стадо;
//    WanderBrain  (wander.js)  — мирный: гуляет вокруг дома, останавливается, смотрит на подошедших.
//  Свои мозги — наследуй Brain и переопредели update.
// ============================================================

export class Brain {
  update(e, ctx, dt) {
    e.velocity.x = 0;
    e.velocity.z = 0;
    return { walking: false, alerted: [] };
  }
}
