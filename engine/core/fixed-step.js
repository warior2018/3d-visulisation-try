// ============================================================
//  FixedStep — фиксированный шаг логики (тикрейт): мир считается ровно rate раз в секунду,
//  сколько бы кадров ни рисовалось. На 30 FPS за кадр проходит 2 тика, на 144 — тик примерно раз в 2–3 кадра;
//  прыжок, рывок, таймеры и урон от этого не зависят (как тикрейт сервера в Overwatch / CS).
//
//    const fixed = new FixedStep({ rate: 60 });
//    // каждый кадр: seconds — сколько прошло настоящего времени
//    fixed.advance(seconds, (dt) => world.step(dt)); // dt всегда 1/60
//    fixed.alpha; // 0…1 — где мы между прошлым и следующим тиком (рисовать с плавностью)
//
//  Накопитель: время кадра копится, и пока накопилось на тик — делаем тик. Остаток ждёт следующего кадра.
//  maxSteps — больше тиков за кадр не делаем: после долгой заминки (подгрузка, сворачивали окно) догонять
//  всё сразу нельзя — тики долгие, кадр выйдет ещё дольше, и игра «утонет» (так называемая спираль смерти).
//  Лишнее время просто выбрасываем: мир на миг замедлился, зато не завис.
// ============================================================

const EPS = 1e-9; // погрешность дробей: 1/60 + 1/60 + ... может не дотянуть до тика на миллиардную

export class FixedStep {
  constructor({ rate = 60, maxSteps = 8 } = {}) {
    this.setRate(rate);
    this.maxSteps = maxSteps;
    this.acc = 0; //     накоплено времени (с), ещё не потраченного на тики
    this.alpha = 0; //   доля пути к следующему тику (0…1)
    this.count = 0; //   сколько тиков всего (номер тика — для сети, повторов, тестов)
    this.dropped = 0; // сколько тиков выбросили из-за заминок (не догоняли)
  }

  // Сменить тикрейт (тиков в секунду): 60, 128... Накопленное время сохраняется
  setRate(rate) {
    this.rate = rate;
    this.dt = 1 / rate;
  }

  // Прошло seconds настоящего времени — сделать нужное число тиков, step(dt) на каждый. Вернёт, сколько сделали
  advance(seconds, step) {
    this.acc += Math.max(0, seconds);
    let n = 0;
    while (this.acc + EPS >= this.dt && n < this.maxSteps) {
      step(this.dt);
      this.acc -= this.dt;
      n++;
      this.count++;
    }
    if (this.acc < 0) this.acc = 0;
    if (this.acc >= this.dt) {
      // упёрлись в maxSteps — остаток не догоняем
      const lost = Math.floor(this.acc / this.dt);
      this.dropped += lost;
      this.acc -= lost * this.dt;
    }
    this.alpha = this.acc / this.dt;
    return n;
  }

  // Забыть накопленное (после меню / паузы: время стояло — догонять нечего)
  reset() {
    this.acc = 0;
    this.alpha = 0;
  }
}
