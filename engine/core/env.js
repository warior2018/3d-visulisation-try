// ============================================================
//  Подсказки (hints) для SDL. Их надо выставить ДО загрузки @kmamal/sdl,
//  поэтому этот файл импортируется в main.js самым первым.
//
//  SDL читает подсказки из переменных окружения с теми же именами.
// ============================================================

// Полный экран на Маке — НАСТОЯЩИЙ: отдельный «рабочий стол» (Space), как по зелёной кнопке.
// Других окон поверх и позади нет. Зелёная кнопка и наша клавиша (F11) — один и тот же режим:
// библиотека знает, когда окно вошло в полный экран и вышло (window.fullscreen всегда честный).
// Раньше было "0" (окно без рамки на весь стол) — из-за того, что размеры окна «врали» во время
// перехода. Теперь движок каждый кадр сверяет настоящий размер окна (Engine.syncSize, рендерер —
// свой resize), поэтому так больше не нужно.
// Если вдруг понадобится старый режим: SDL_VIDEO_MAC_FULLSCREEN_SPACES=0 npm start
process.env.SDL_VIDEO_MAC_FULLSCREEN_SPACES ??= "1";

// Зажатая клавиша на Маке — просто зажатая клавиша (WASD, Q, E...), а не меню букв с акцентами
// (à á â ä…): иначе слева вверху всплывала полоска-подсказка, как у текстового поля.
// SDL всё время держит окно «готовым к вводу текста» — для игры это не нужно.
// Вернуть системное поведение: SDL_MAC_PRESS_AND_HOLD=1 npm start
process.env.SDL_MAC_PRESS_AND_HOLD ??= "0";
