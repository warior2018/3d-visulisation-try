import { Profiler } from "../../../engine/core/profiler.js";
let ok = 0, bad = 0;
const check = (name, cond, info = "") => { cond ? ok++ : bad++; console.log((cond ? "OK  " : "FAIL") + " " + name + (info ? "  (" + info + ")" : "")); };
let clock = 0;
const p = new Profiler({ now: () => clock, watchGc: false, statsEvery: Infinity, memoryEvery: Infinity, graceFrames: 0 });
const A = p.register("AI"), PATH = p.register("PATH", A), H = p.register("HUD"), Z = p.register("NEVER");
check("выключен/пусто — понятное сообщение", p.report()[0].includes("NO DATA"));
p.enabled = true;
p.hitchContext = () => "MOBS 50";
const dumps = [];
p.onDump = (lines) => dumps.push(lines);
const frame = (a, path, h, work, gap) => {
  p.begin(A); clock += a - path; p.begin(PATH); clock += path; p.end(PATH); p.end(A);
  p.begin(H); clock += h; p.end(H); clock += Math.max(0, gap - a - h);
  p.endFrame(work, gap);
};
for (let i = 0; i < 100; i++) frame(4, 1, 2, 8, 16);
let r = p.report("test");
console.log(r.map((l) => "     " + l).join("\n"));
check("заголовок: работа ср. 8, промежуток ср. 16", r[0].includes("WORK AVG 8.00") && r[0].includes("GAP AVG 16.0"), r[0]);
check("дерево: AI и под ним PATH с отступом", r.some((l) => l.startsWith("  AI AVG 4.00")) && r.some((l) => l.startsWith("    PATH AVG 1.00")));
check("доля AI 50%", r.some((l) => l.includes("AI AVG 4.00 MAX 4.00 (50.0%)")));
check("система, что ни разу не работала, не показана", !r.some((l) => l.includes("NEVER")));
check("рывков нет — авто-срезов нет", dumps.length === 0);
// 4 рывка — мало; 5-й — авто-срез; ещё рывки в ту же минуту — нового среза нет
for (let i = 0; i < 4; i++) frame(60, 0, 2, 70, 75);
check("4 рывка за минуту — авто-среза нет", dumps.length === 0);
frame(60, 0, 2, 70, 75);
check("5-й рывок — авто-срез", dumps.length === 1 && dumps[0][0].includes("auto: many hitches"));
check("в срезе — список рывков с контекстом", dumps[0].filter((l) => l.startsWith("  -") && l.includes("MOBS 50")).length === 5);
for (let i = 0; i < 5; i++) frame(60, 0, 2, 70, 75);
check("ещё рывки в ту же минуту — не чаще раза в минуту", dumps.length === 1);
clock += 61000;
for (let i = 0; i < 5; i++) frame(60, 0, 2, 70, 75);
check("через минуту — снова может", dumps.length === 2);
p.onDump = null;
for (let i = 0; i < 5; i++) frame(60, 0, 2, 70, 75);
check("без onDump — ничего не падает", true);
console.log(`\nитого: ${ok} OK, ${bad} FAIL`);
process.exit(bad ? 1 : 0);
